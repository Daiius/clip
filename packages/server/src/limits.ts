/**
 * 投入の上限（prd/02 §5）。
 *
 * **このファイルは web からも import される**（`server/limits`）。投入前にクライアント側で
 * サイズを弾くため（prd/03 §1.4）に必要で、**値を web 側へ書き写さない**のが目的。
 * 書き写すと、サーバーの上限を上げたときにクライアントだけが古い値のまま厳しくなり、
 * **正しい画像が投入できなくなる**（利用者が回避できない向きの誤判定になる）。
 *
 * そのため、**ここには zod も drizzle も持ち込まない**。依存を足すとブラウザ側の束に
 * サーバー専用のコードが混ざる。定数だけを置くこと。
 */

/** 1エントリあたりの画像の上限（prd/02 §5）。 */
export const MAX_IMAGE_BYTES = 20 * 1024 * 1024

/**
 * テキストの上限（prd/02 §5）。**`mediumtext` の上限そのもの**（16,777,215 バイト・UTF-8 換算）。
 *
 * 実用上ここに当たることは想定しないが、**上限を超えた入力を DB に投げると 500 になる**。
 * 利用者の入力に起因する失敗は、DB エラーではなく明示的な 4xx で返す。
 */
export const MAX_TEXT_BYTES = 16_777_215

/**
 * ファイル名の上限（`varchar(255)`）。**超えた分は切り詰める**。
 *
 * ファイル名はダウンロード時の既定名でしかなく、**長いという理由で投入を拒む価値がない**
 * （ペースト経由ではそもそも無い。prd/02 §2）。ただし DB 列に収まらないものをそのまま
 * insert すると 500 になるので、保存前に丸める。
 */
export const MAX_FILE_NAME_LENGTH = 255

/**
 * 1つの共有セットに入れられる件数（prd/02 §5）。
 *
 * 一覧のページサイズ（prd/03 §2）に揃える。無制限にする理由がなく、既にある数字を使う。
 */
export const MAX_SHARE_CLIPS = 50

/**
 * 共有トークンの寿命（prd/02 §5）。**UI で選ばせない。**
 *
 * 想定する使い方は「発行 → 渡す → 読ませる」で秒から分で終わるため、選択肢を出しても
 * 毎回どうでもいい判断を強いるだけになる。短すぎたと分かったらここを変える。
 *
 * ⚠ **これは利便の設定ではなく防御の一部である**（prd/04 §3.1）。共有 URL はパスにトークンを
 * 載せるので、**こちらで制御できない前段のアクセスログには残りうる**。そこに対する唯一の
 * 手当てが「寿命を短く保つこと」であり、伸ばすほど被害の窓が広がる。
 */
export const SHARE_TTL_MS = 10 * 60 * 1000
